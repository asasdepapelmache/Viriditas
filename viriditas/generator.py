"""Build the local repository with `git fast-import`.

The import stream is piped straight into `git fast-import`. Nothing is
accumulated in memory or written to a temporary file, which is what keeps a
hundred thousand commits down to a few seconds.
"""

from __future__ import annotations

import calendar
import datetime as dt
import os
import random
import shutil
import stat
import subprocess
import sys
import time
from pathlib import Path

from .config import MIN_UNIX, Config
from .github import ToolError, git, git_path

# Throughput used only by `plan` to estimate a duration. `generate` measures and
# reports the real figure.
ESTIMATED_COMMITS_PER_SECOND = 20_000

PROGRESS_EVERY = 2_000
BAR_WIDTH = 32

GENERATED_README = """# {repo}

Generated by Viriditas: {total:,} backdated commits from {first} to {last}.

Every commit rewrites `{activity}` with the day it belongs to. The history
carries no other content; this repository exists only to render a contribution
graph.

https://github.com/topics/viriditas
"""


class GenerateError(Exception):
    """Generation failed, with a message meant for the user."""


def day_window(day: dt.date, tz_offset: int) -> tuple[int, int]:
    """The Unix timestamp range that falls on `day` in the configured offset.

    The lower bound is clamped to MIN_UNIX. That clamp is what makes 1969-12-31
    work: with a negative offset only its last hours exist after the epoch.
    """
    midnight = calendar.timegm((day.year, day.month, day.day, 0, 0, 0, 0, 0, 0))
    midnight -= tz_offset
    low = max(midnight, MIN_UNIX)
    high = midnight + 86_399
    if high < low:
        raise GenerateError(
            f"{day} is unreachable with offset {tz_offset}: the whole day falls "
            "before the Unix epoch."
        )
    return low, high


def timestamps_for_day(
    day: dt.date, count: int, tz_offset: int, rng: random.Random
) -> list[int]:
    """`count` strictly increasing timestamps spread across the day."""
    low, high = day_window(day, tz_offset)
    span = high - low
    if count == 1:
        return [low + span // 2]

    slot = max(1, span // count)
    stamps: list[int] = []
    previous = low - 1
    for index in range(count):
        stamp = low + index * slot + rng.randrange(0, slot)
        stamp = min(max(stamp, previous + 1), high)
        stamps.append(stamp)
        previous = stamp
    return stamps


def unix_to_local_date(stamp: int, tz_offset: int) -> dt.date:
    """The day GitHub attributes the commit to (the offset stored in it)."""
    return (dt.datetime(1970, 1, 1) + dt.timedelta(seconds=stamp + tz_offset)).date()


def unix_to_local_string(stamp: int, tz_offset: int) -> str:
    moment = dt.datetime(1970, 1, 1) + dt.timedelta(seconds=stamp + tz_offset)
    sign = "-" if tz_offset < 0 else "+"
    offset = abs(tz_offset)
    return (
        f"{moment:%Y-%m-%d %H:%M:%S} "
        f"{sign}{offset // 3600:02d}{(offset % 3600) // 60:02d}"
    )


def raw_to_display(raw: str) -> str:
    """'3600 -0300' -> '1969-12-31 22:00:00 -0300'."""
    stamp_text, tz_text = raw.split()
    sign = -1 if tz_text[0] == "-" else 1
    offset = sign * (int(tz_text[1:3]) * 3600 + int(tz_text[3:5]) * 60)
    return unix_to_local_string(int(stamp_text), offset)


def raw_bounds(workdir: Path) -> tuple[str, str] | None:
    """Raw dates of the first and last commit, or None for an empty repository.

    Deliberately uses `--date=raw`: any `git log` that *formats* the date aborts
    with "Timestamp before Unix epoch" on a 1969 commit. See the README.
    """
    try:
        output = git(
            "log", "--reverse", "--date=raw", "--format=%ad", "main", cwd=workdir
        )
    except ToolError:
        return None
    lines = [line.strip() for line in output.splitlines() if line.strip()]
    if not lines:
        return None
    return lines[0], lines[-1]


def commit_count(workdir: Path) -> int | None:
    raw = git("rev-list", "--count", "main", cwd=workdir, check=False).strip()
    return int(raw) if raw.isdigit() else None


def _blob(mark: int, content: bytes) -> bytes:
    return b"blob\nmark :%d\ndata %d\n%s\n" % (mark, len(content), content)


def _on_rmtree_error(func, path, _exc_info):
    """Retry hook: git pack files are read-only, which trips rmtree on Windows."""
    try:
        os.chmod(path, stat.S_IWRITE)
        func(path)
    except OSError as exc:
        raise GenerateError(
            f"could not delete {path}: {exc}\n"
            "Close anything holding that folder open (editor, terminal, "
            "antivirus) and try again."
        ) from None


def remove_workdir(workdir: Path) -> bool:
    """Delete the working directory. True when something was removed."""
    if not workdir.exists():
        return False
    shutil.rmtree(workdir, onexc=_on_rmtree_error)
    return True


def _prepare_workdir(config: Config, force: bool) -> Path:
    workdir = config.workdir
    if workdir.exists():
        if not force:
            raise GenerateError(
                f"{workdir} already exists. Pass --force to delete and rebuild "
                "it, or run `viriditas clean` first. The remote is not touched "
                "either way."
            )
        remove_workdir(workdir)
    workdir.mkdir(parents=True)
    git("init", "--quiet", "--initial-branch=main", ".", cwd=workdir)
    return workdir


def _readme_blob(config: Config, mark: int, total: int, first: str, last: str) -> bytes:
    body = GENERATED_README.format(
        repo=config.repo_name,
        total=total,
        first=first,
        last=last,
        activity=config.activity_file,
    ).encode()
    return _blob(mark, body)


def generate(
    config: Config,
    schedule: dict[dt.date, int],
    force: bool = False,
    progress: bool = True,
) -> dict:
    """Create the local repository and return a summary of what was written."""
    if git_path() is None:
        raise GenerateError("git not found on PATH.")

    total = sum(schedule.values())
    if total == 0:
        raise GenerateError("the schedule is empty; nothing to generate.")
    if config.name == "auto" or config.email == "auto":
        raise GenerateError(
            "identity was not resolved; call config.with_identity() first."
        )

    workdir = _prepare_workdir(config, force)
    rng = random.Random(f"{config.seed}:commits")
    tz_offset = config.tz_offset_seconds
    author = f"{config.name} <{config.email}>"
    days = sorted(schedule)

    process = subprocess.Popen(
        [git_path(), "fast-import", "--date-format=raw", "--quiet"],
        cwd=str(workdir),
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )

    started = time.perf_counter()
    written = 0
    mark = 0
    first_stamp: int | None = None
    last_stamp: int | None = None

    try:
        assert process.stdin is not None
        for day in days:
            stamps = timestamps_for_day(day, schedule[day], tz_offset, rng)
            for index, stamp in enumerate(stamps, start=1):
                written += 1
                mark += 1

                payload = f"{day.isoformat()} #{index}\n".encode()
                chunk = [_blob(mark, payload)]
                modifications = [f"M 100644 :{mark} {config.activity_file}"]

                if written == total and config.add_readme:
                    mark += 1
                    chunk.append(
                        _readme_blob(
                            config,
                            mark,
                            total,
                            unix_to_local_string(first_stamp or stamp, tz_offset),
                            unix_to_local_string(stamp, tz_offset),
                        )
                    )
                    modifications.append(f"M 100644 :{mark} README.md")

                message = f"{rng.choice(config.messages)}\n".encode()
                chunk.append(
                    (
                        "commit refs/heads/main\n"
                        f"author {author} {stamp} {config.timezone}\n"
                        f"committer {author} {stamp} {config.timezone}\n"
                    ).encode()
                )
                chunk.append(b"data %d\n%s" % (len(message), message))
                chunk.append(("\n".join(modifications) + "\n\n").encode())

                process.stdin.write(b"".join(chunk))

                if first_stamp is None:
                    first_stamp = stamp
                last_stamp = stamp

                if progress and written % PROGRESS_EVERY == 0:
                    _render_progress(written, total, started)

        process.stdin.close()
    except BrokenPipeError:
        pass

    _, stderr = process.communicate()
    if progress:
        _render_progress(written, total, started, final=True)
    if process.returncode != 0:
        raise GenerateError(
            f"git fast-import failed with exit code {process.returncode}:\n"
            f"{stderr.decode('utf-8', 'replace').strip()}"
        )

    git("config", "user.name", config.name, cwd=workdir)
    git("config", "user.email", config.email, cwd=workdir)
    # Materialise the tree so the repository is browsable. A failure here is not
    # fatal: the objects are already written and the push would still work.
    git("reset", "--hard", "main", cwd=workdir, check=False)

    return {
        "workdir": workdir,
        "commits_written": written,
        "commits_in_repo": commit_count(workdir),
        "elapsed": time.perf_counter() - started,
        "first": unix_to_local_string(first_stamp, tz_offset),
        "last": unix_to_local_string(last_stamp, tz_offset),
    }


def append(
    config: Config, schedule: dict[dt.date, int], progress: bool = True
) -> dict:
    """Add commits on top of the existing main branch (used by `topup`)."""
    workdir = config.workdir
    if not workdir.exists():
        raise GenerateError(f"{workdir} does not exist.")
    if config.name == "auto" or config.email == "auto":
        raise GenerateError("identity was not resolved before append().")

    total = sum(schedule.values())
    if total == 0:
        raise GenerateError("nothing to append.")

    rng = random.Random(f"{config.seed}:topup:{min(schedule)}")
    tz_offset = config.tz_offset_seconds
    author = f"{config.name} <{config.email}>"

    process = subprocess.Popen(
        [git_path(), "fast-import", "--date-format=raw", "--quiet"],
        cwd=str(workdir),
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )

    started = time.perf_counter()
    written = 0
    mark = 0
    assert process.stdin is not None
    for day in sorted(schedule):
        for index, stamp in enumerate(
            timestamps_for_day(day, schedule[day], tz_offset, rng), start=1
        ):
            written += 1
            mark += 1
            payload = f"{day.isoformat()} #{index}\n".encode()
            message = f"{rng.choice(config.messages)}\n".encode()

            chunk = [_blob(mark, payload)]
            chunk.append(
                (
                    "commit refs/heads/main\n"
                    f"author {author} {stamp} {config.timezone}\n"
                    f"committer {author} {stamp} {config.timezone}\n"
                ).encode()
            )
            chunk.append(b"data %d\n%s" % (len(message), message))
            if written == 1:
                # Without this the import would start a new root commit.
                chunk.append(b"from refs/heads/main^0\n")
            chunk.append(f"M 100644 :{mark} {config.activity_file}\n\n".encode())
            process.stdin.write(b"".join(chunk))

            if progress and written % 100 == 0:
                _render_progress(written, total, started)

    process.stdin.close()
    _, stderr = process.communicate()
    if progress:
        _render_progress(written, total, started, final=True)
    if process.returncode != 0:
        raise GenerateError(
            f"git fast-import failed with exit code {process.returncode}:\n"
            f"{stderr.decode('utf-8', 'replace').strip()}"
        )

    git("reset", "--hard", "main", cwd=workdir, check=False)
    return {
        "commits_written": written,
        "commits_in_repo": commit_count(workdir),
        "elapsed": time.perf_counter() - started,
    }


def _render_progress(done: int, total: int, started: float, final: bool = False):
    elapsed = max(time.perf_counter() - started, 1e-6)
    filled = int(BAR_WIDTH * done / total)
    bar = "#" * filled + "-" * (BAR_WIDTH - filled)
    sys.stderr.write(
        f"\r  [{bar}] {done:>8,}/{total:,} "
        f"({100 * done / total:5.1f}%)  {done / elapsed:,.0f}/s"
    )
    if final:
        sys.stderr.write("\n")
    sys.stderr.flush()
